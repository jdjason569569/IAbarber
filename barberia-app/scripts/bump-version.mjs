// Bumps the app patch version and keeps the Android build and the version shown in the UI in sync.
// Run by the git pre-commit hook; it can also be run by hand with `npm run version:bump`.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const appDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = join(appDir, 'package.json');
const lockPath = join(appDir, 'package-lock.json');
const gradlePath = join(appDir, 'android', 'app', 'build.gradle');
const versionFilePath = join(appDir, 'src', 'app', 'core', 'config', 'app-version.ts');

const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const writeJson = (path, data) => writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`);

const pkg = readJson(packagePath);
const [major, minor, patch] = pkg.version.split('.').map(Number);
const nextVersion = `${major}.${minor}.${patch + 1}`;

pkg.version = nextVersion;
writeJson(packagePath, pkg);

const lock = readJson(lockPath);
lock.version = nextVersion;
if (lock.packages?.['']) {
  lock.packages[''].version = nextVersion;
}
writeJson(lockPath, lock);

const gradle = readFileSync(gradlePath, 'utf8');
const nextGradle = gradle
  .replace(/versionCode (\d+)/, (_, code) => `versionCode ${Number(code) + 1}`)
  .replace(/versionName "[^"]*"/, `versionName "${nextVersion}"`);
writeFileSync(gradlePath, nextGradle);

writeFileSync(
  versionFilePath,
  `// Generated by scripts/bump-version.mjs on every commit. Do not edit by hand.\nexport const APP_VERSION = '${nextVersion}';\n`,
);

console.log(`App version bumped to ${nextVersion}`);
